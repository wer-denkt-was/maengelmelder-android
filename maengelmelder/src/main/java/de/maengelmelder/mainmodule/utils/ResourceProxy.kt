    /**
     * Check whether a file exists in Assets folder.
     * @param c [Context] object
     * @param path path to the file in assets folder (After the "assets" path)
     */
    fun fileExistsInAssets(c: Context, path: String): Boolean {
        val am = c.resources.assets
        val inpStream = try { am.open(path) } catch (e: IOException) { null }
        val exists = inpStream != null
        inpStream?.close()
        return exists
