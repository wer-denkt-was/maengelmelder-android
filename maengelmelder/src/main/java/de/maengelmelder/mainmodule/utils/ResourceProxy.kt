    /**
     * Combine the list of marker bitmaps into one.
     * To see the example, zoom out the map until you see a group of 3 markers on top of each other
     *
     * @param bitmaps list of [Bitmap] marker images
     * @param displayCount number of marker bitmaps that should be shown on map. Usually 3
     * @return the combined bitmap marker image
     */
    private fun combineBitmapsForMarker(bitmaps: List<Bitmap>, displayCount: Int): Bitmap {
        // Prepare offset and dimensions for the grouped markers
        val xOffset = bitmaps[1].width / 4f
        val yOffset = xOffset / 2f
        val bitWidth = bitmaps[1].width + (if (displayCount == 3) xOffset * 2 else xOffset)
        val bitmapToUse = if (displayCount == 3) bitmaps[2] else bitmaps[1]
        val bitHeight = bitmapToUse.height + yOffset

        // Containers for the group marker
        val finalBitmap = Bitmap.createBitmap(bitWidth.toInt(), bitHeight.toInt(), Bitmap.Config.ARGB_8888)
        val canvas = Canvas(finalBitmap)

        // Set the left position (1st marker)
        canvas.drawBitmap(bitmaps[0], 0f, 0f, null)
        // Set right position for 3+ messages in a group
        if (displayCount == 3) {
            canvas.drawBitmap(bitmaps[1], 2f * xOffset, 0f, null)
        }
        // Set the lower middle position
        canvas.drawBitmap(bitmapToUse, xOffset, yOffset, null)
        return finalBitmap
    }

    /**
     * Call to [Resources.getIdentifier]
     */
    @SuppressLint("DiscouragedApi")
    private fun doGetResourceId(ctx: Context, name: String, defType: String) : Int {
        return ctx.resources.getIdentifier(name, defType, ctx.packageName)
    }

    /**
     * Converts [LayerDrawable] to [BitmapDrawable]. Since some Map engine only accepts [BitmapDrawable] and the markers themselves are
     * structured on top of each other (marker background and icon), this method can easily transform it
     *
     * @param res [Resources]
     * @param dlayer the [LayerDrawable] of the loaded marker
     * @return [BitmapDrawable] that contains the marker image
     *
     * @see getMarker
     */
    private fun layerToBitmapDrawable(res: Resources, dlayer: LayerDrawable): BitmapDrawable {
        val bitmap = Bitmap.createBitmap(dlayer.intrinsicWidth, dlayer.intrinsicHeight, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)
        dlayer.setBounds(0, 0, dlayer.intrinsicWidth, dlayer.intrinsicHeight)
        dlayer.draw(canvas)

        val bmpD = BitmapDrawable(res, bitmap)
        bmpD.setBounds(0, 0, dlayer.intrinsicWidth, dlayer.intrinsicHeight)
        return bmpD
    }

    /**
     * Get the photo file path. Required in Android 7.0+ since the photo-saving functionality from camera changed a bit
     *
     * @param c Context
     * @param fileName the name of the file without extension
     * @param ext Extension without dot (.)
     *
     * @return The file containing the photo
     */
    fun getPhotoFilePath(c: Context, fileName: String, ext: String): File {
        val path = File(c.filesDir, "images")
        // If u don't create the folder first, the camera intent will return without any error (and ofc, no images) !!!
        if (!path.exists()) path.mkdir()
        return File(path, "$fileName.$ext")
    }

    /**
     * Caller to [doSaveImageToMediaStore] with [File] as param
     * @param context Context object
     * @param imageFile valid Image file
     */
    @Throws(IOException::class, IllegalArgumentException::class, FileNotFoundException::class)
    fun saveImageToMediaStore(context: Context, imageFile: File) {
        try {
            val imageBitmap = BitmapFactory.decodeFile(imageFile.absolutePath)
            saveImageToMediaStore(context, imageFile.name, imageBitmap)
        } catch (e: IOException) {
            throw e
        } catch (e: IllegalArgumentException) {
            throw e
        } catch (e: FileNotFoundException) {
            throw e
        }
    }

    /**
     * Beginning from Android 10+, images from app-specific folders are no longer scanned by gallery apps.
     * Therefore, images taken from camera must then be saved through MediaStore API so it is available in gallery apps
     *
     * @param context Context object
     * @param filename name of the file shown in gallery (<filename>.<ext>)
     * @param imageBitmap [Bitmap] object
     */
    @Throws(IOException::class, FileNotFoundException::class)
    fun saveImageToMediaStore(context: Context, filename: String, imageBitmap: Bitmap): Uri? {
        val contentResolver = context.contentResolver
        var transferUri: Uri? = null
        if (contentResolver != null) {
            // build content values
            val contentValues = ContentValues().apply {
                put(MediaStore.MediaColumns.DISPLAY_NAME, filename)
                put(MediaStore.MediaColumns.MIME_TYPE, "image/jpg")
                put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_PICTURES)
            }

            try {
                // Insert with mediastore API
                transferUri = contentResolver.insert(
                    MediaStore.Images.Media.EXTERNAL_CONTENT_URI,
                    contentValues
                )?: throw IOException("Failed to create transfer uri for app-specific image")

                // save the insertion Uri
                contentResolver.openOutputStream(transferUri)?.use {
                    if (!imageBitmap.compress(Bitmap.CompressFormat.JPEG, 100, it)) {
                        throw IOException("Failed to save bitmap to mediastore")
                    }
                }
            } catch (e: IOException) {
                transferUri?.let { u -> contentResolver.delete(transferUri, null, null) }
                throw e
            } catch (e: FileNotFoundException) {
                throw e
            }
        }

        return transferUri
    }

