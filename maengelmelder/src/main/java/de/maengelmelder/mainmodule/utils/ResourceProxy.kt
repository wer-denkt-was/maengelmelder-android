    /**
     * Reads a file from assets folder and return the content as string
     */
    fun readFromAssets(c: Context, filePath: String): String {
        return c.assets.open(filePath).bufferedReader().use { it.readText() }
    }

    /**
     * Reads serialized object from intent.
     * Starting from Android SDK 33, [Intent.getSerializableExtra] is deprecated
     */
    @Suppress("DEPRECATION")
    fun<T: java.io.Serializable> getSerializeableExtra(i: Intent, key: String, clazz: Class<T>): T? {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            return i.getSerializableExtra(key, clazz)
        }
        return i.getSerializableExtra(key) as? T
    }

    /**
     * Transform URL into <a>-Tag URLs, effectively becoming HTML text
     */
    fun linkifyText(text: String): String {
        val regex = Regex("""\b((?:https://|www\.)[^\s<]+)""", RegexOption.IGNORE_CASE)
        val linkedText = regex.replace(text) { matchResult ->
            val url = matchResult.value.let {
                if (it.startsWith("www.", ignoreCase = true)) "https://$it" else it
            }
            """<a href="$url">${matchResult.value}</a>"""
        }
        val htmlText = linkedText.replace("\n", "<br/>")
        return htmlText
    }

    /**
     * Retrieves additional map layers
     */
    fun getAdditionalMapLayerInfo(c: Context): Pair<LayerswitcherInfo?, List<MapLayerInfo>>? {
        val info = readFromAssets(c, "mm-geojson/settings.json")
        val infoJSON = try { JSONObject(info) } catch (e: Exception) { null }
        if (infoJSON == null) return null

        val mapLayers = arrayListOf<MapLayerInfo>()

        infoJSON.optJSONArray("layers")?.let {
            (0..<it.length()).forEach { idx ->
                val newLayer = MapLayerInfo.fromJSON(it.getJSONObject(idx))
                mapLayers.add(newLayer)
            }
        }

        var layerInfo: LayerswitcherInfo? = null
        infoJSON.optJSONObject("info")?.let { s ->
            layerInfo = LayerswitcherInfo(
                singleSwitch = s.optBoolean("single_switch", false),
                switchName = s.optString("switch_name")
            )
        }

        return Pair(layerInfo, mapLayers)
    }

    /**
     *  parse queryparameter (e.g. a=1&b=2&c=3) into map of String as key and Any? as value
     *  @param queryParameter query parameters in string
     *  @return returns map of key-value
     */
    fun parseQueryParameter(queryParameter: String): Map<String, Any?> {
        // Log.d("ParseQueryParameter", queryParameter)

        val params = queryParameter.split("&")
        val hash: HashMap<String, Any?> = hashMapOf()
        hash["attribute_values"] = hashMapOf<String, Any?>()

        val attributePattern = Regex("^(selected|force)_attribute(\\d+)$")
        params.forEach { p ->
            val keyVal = p.split("=")
            if (keyVal.size >= 2) {
                // Special case for attribute
                val attrPatternResult = attributePattern.find(keyVal[0])
                val decodedValue = URLDecoder.decode(keyVal[1])
                if (attrPatternResult != null && attrPatternResult.groupValues.size > 1) {
                    val type = attrPatternResult.groupValues[1]
                    val attrId = attrPatternResult.groupValues[2]
                    (hash["attribute_values"] as HashMap<String, Any?>).let { m ->
                        if (type == "force" // Forced
                            // Not forced and the value is not filled yet (we prioritize forced over selected)
                            || (type == "selected" && !m.containsKey(attrId + "_force"))
                            ) {
                            m[attrId] = decodedValue
                            m[attrId + "_force"] = type == "force"
                        }
                    }
                } else {
                    hash[keyVal[0]] = decodedValue
                }
            }
        }
        return hash
    }

    /**
     * Validate the given query parameter (e.g. a=1&b=2&c=3) whether it can be used as parameter for new bms message
     * Used in deeplinking activity for validating the URL
     *
     * @param c Context
     * @param query Query parameter in string
     * @param onDone function to be called after the validation is done
     */
    fun validateBrowsableUrlQuery(c: Context, query: String, onDone: (Boolean, BrowsableQueryParam?, String) -> Unit) {
        val param = parseQueryParameter(query)
        val forceLoc = try { (param["force_loc"] as String).toInt() == 1 } catch (e: Exception) { false }
        val locationAvailable = param.contains("lat") && param.contains("lon")
        val lat = try { (param["lat"] as String).toDouble() } catch (e: Exception) { 0.0 }
        val lon = try { (param["lon"] as String).toDouble() } catch (e: Exception) { 0.0 }
        val forceTypeid = try { (param["force_typeid"] as String).toLong() } catch (e: Exception) { 0 }
        val typeid = try { (param["selected_typeid"] as String).toLong() } catch (e: Exception) { 0 }

        /**
         * TODO: implement `filter_typeid=2,3,4,5,6` to filter the list of viewable categories, just like frontend wizard.
         */

        // Check lat lon
        val forceLocation = if (locationAvailable) forceLoc else false
        val selectedLL = LatLng(lat, lon);

        // Check typeid
        val forceType = forceTypeid > 0L
        val selectedType = if (forceTypeid > 0L) forceTypeid else typeid

        if (locationAvailable && (selectedLL.latitude == 0.0 || selectedLL.longitude == 0.0)) {
            // Invalid lat/lon (both of them must exist)
            onDone.invoke(false, null, c.getString(R.string.err_qrscan_invalid_location))
            return
        }

        if (selectedType > 0L) {
            // retrieve system/domain and launch message creation if the given selectedType is valid
            DomainUtil.isMessageCategoryAvailable(c, lat, lon, selectedType, forceType) { category, failedToRetrieve ->
                if (category == null) {
                    // Typeid is not found in any domain queried by the location
                    onDone.invoke(false, null, c.getString(R.string.deeplink_err_type_not_found))
                } else {
                    // Category is valid. Launch message creation activity with the correct params
                    val param = BrowsableQueryParam().apply {
                        this.category = category
                        this.lat = selectedLL.latitude
                        this.lon = selectedLL.longitude
                        this.attributeValues = (param["attribute_values"] as HashMap<String, Any?>)
                        this.forceLocation = forceLocation
                        this.forceType = forceType
                    }
                    onDone.invoke(true, param, "")
                }
            }
        } else {
            // no category, no location? Just empty message creation
            val param = BrowsableQueryParam().apply {
                this.category = null
                this.lat = selectedLL.latitude
                this.lon = selectedLL.longitude
                this.forceLocation = forceLocation
                this.attributeValues = (param["attribute_values"] as HashMap<String, Any?>)
            }
            onDone.invoke(true, param, "")
        }
    }

