    /**
     * Get the [Drawable] marker identified by its name and color. The drawable will also be cached temporarily using its name and color.
     * The method uses the base marker R.drawable.mm_marker and modifies it based on the given id and color. The base marker has the id
     * "frame" to indicate the marker's frame color and "icon" to indicate marker's icon. If the marker exists beforehand,
     * it will be returned instead of recreating it
     *
     * @param context Context
     * @param color the color of the marker. Allowed are red, blue, green, green2, yellow, white, grey
     * @param id the marker's Id. Check the drawable folder for available Ids
     * @param selected if true, it will replace the frame of the marker to the selected one (green_sel, red_sel, etc.)
     *
     * @see LayerDrawable.setDrawableByLayerId
     *
     * @return the Drawable marker with corresponding color and id.
     */
    fun getMarker(context: Context, color: String, id: String, selected: Boolean = false): Drawable {
        // Sets the marker's name for identification
        var name = "marker_${id}_${color}"
        if (selected) name += "_sel"

        // Find it on the map first for existing marker
        var marker = mMarkerMap[name]
        val frameSuffix = MMConstants.SpecializedMarkerFrameSuffix

        if (marker == null) {
            // Get the correct resource id for frame and icon
            val colorString = if (frameSuffix.isNotEmpty()) "${color}_${frameSuffix}" else color
            val frameName = if (!selected) colorString else "${colorString}_sel"
            val baseMarker = ContextCompat.getDrawable(context, R.drawable.mm_marker) as LayerDrawable
            var iconResId = doGetResourceId(context, "symbol_$id", "drawable")
            var frameResId = doGetResourceId(context, frameName, "drawable")

            // Revert marker icon to symbol_0 if it does not exist
            if (iconResId == 0) {
                iconResId = R.drawable.symbol_0
            }

            // Revert to normal frame color if it does not exist
            if (frameResId == 0) {
                frameResId = doGetResourceId(context, color, "drawable")
            }

            val iconRes = ContextCompat.getDrawable(context, iconResId)
            var frameRes = try {
                ContextCompat.getDrawable(context, frameResId)
            } catch (e: Exception) {
                // Exception may happen when the given color from server is not found inside the App
                // Therefore we use "white" color as default
                null
            }
            if (frameRes == null) {
                frameRes = ContextCompat.getDrawable(context, doGetResourceId(context, "white", "drawable"))
            }

            // Replace the base marker's icon and frame to the picked ones
            baseMarker.setDrawableByLayerId(R.id.frame, frameRes)
            baseMarker.setDrawableByLayerId(R.id.icon, iconRes)

            // For markers with ID above 199 or 18, they don't have bottom padding to compensate the marker's pointy part
            // Instead, we add it ourselves, so the icon is correctly positioned inside the marker
            val idInt = try { id.toInt() } catch (e: NumberFormatException) { -1 }
            // Per T17958, MING icons already have bottom margin so we don't need to add it programmatically
            if ((idInt in 200..999) || idInt == 18) {
                try {
                    val bottom = 9 * context.resources.displayMetrics.density
                    baseMarker.setLayerInset(1, 0, 0, 0, bottom.toInt())
                } catch (e: Exception) { }
            }

            // Create a bitmap drawable from the given marker, since the map can only accept bitmaps
            marker = layerToBitmapDrawable(res = context.resources, dlayer = baseMarker)
            mMarkerMap[name] = marker
        }

        return marker
    }

